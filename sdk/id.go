package dsc

import "dsc/jobs"

// NewID 生成跨表、跨文件唯一的标识：<kind>-<16 位小写十六进制>（8 字节熵）。
//
// 为什么插件需要这个：插件自有的状态条目（记忆、产物索引等）经常要「换个文件也认
// 得出同一条」。自增主键在不同文件里必然重复（第 1 条在每个库里都叫 1），进程内
// 序号会随重启归零，只有足够宽的随机值成立——8 字节（64 位）在几万条规模下碰撞
// 概率可以忽略。
//
// 与宿主内部 ShortID（7 位十六进制、同表查重兜底、给人看的短标识）口径不同：
// 那个 28 位熵靠「撞了就重生成」兜底，跨文件没有可查重的表，所以这里必须够宽。
// 两处共用同一实现（jobs.NewID），插件侧不重复写一份随机 id。
func NewID(kind string) string { return jobs.NewID(kind, 8) }
